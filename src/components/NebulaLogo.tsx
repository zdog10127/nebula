export default function NebulaLogo({ size = 32, className = '' }: { size?: number; className?: string }) {
  const uid = useId()
  const blurId = `nebula-logo-blur-${uid}`
  const coreGlowId = `nebula-logo-core-glow-${uid}`

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 200 200"
      className={className}
      role="img"
      aria-label="Nébula"
    >
      <defs>
        <filter id={blurId} x="-60%" y="-60%" width="220%" height="220%">
          <feGaussianBlur stdDeviation="4.6" />
        </filter>
        <radialGradient id={coreGlowId} cx="50%" cy="50%" r="50%">
          <stop offset="0%" stopColor="#ffffff" />
          <stop offset="45%" stopColor="#ecfeff" />
          <stop offset="100%" stopColor="#a5f3fc" stopOpacity="0" />
        </radialGradient>
      </defs>

      {/* the gas-cloud spiral arm, blurred into a continuous swirl */}
      <g filter={`url(#${blurId})`} fill="none">
        {ARM_SEGMENTS.map(([x1, y1, x2, y2, color, width, opacity], i) => (
          <line
            key={i}
            x1={x1}
            y1={y1}
            x2={x2}
            y2={y2}
            stroke={color}
            strokeWidth={width}
            strokeLinecap="round"
            opacity={opacity}
          />
        ))}
      </g>

      {/* bright glowing core at the spiral's origin */}
      <circle cx="100" cy="100" r="30" fill={`url(#${coreGlowId})`} />
      <circle cx="100" cy="100" r="11.5" fill="#ffffff" />
      <circle cx="100" cy="100" r="6.5" fill="#ecfeff" />

      {/* a few distant stars */}
      <circle cx="26" cy="155" r="2.4" fill="#e0f7fa" opacity="0.8" />
      <circle cx="172" cy="150" r="2" fill="#f0abfc" opacity="0.7" />
      <circle cx="30" cy="40" r="1.8" fill="#e0f7fa" opacity="0.6" />
    </svg>
  )
}
